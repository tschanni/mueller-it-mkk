import { createRegistrationRecovery, registrationKey, retryDelay } from './registrationRecovery';

const input = { name: 'Player', email: 'player@example.test', password: 'private-password-123' };
const response = (status: number, data: unknown, delay?: string): Response => ({ status, json: async () => data,
  headers: { get: (name: string) => name === 'Retry-After' ? delay ?? null : null },
} as Response);
const success = () => response(200, { state: 'SUCCEEDED', code: 'REGISTRATION_ACCEPTED' });
const pending = () => response(202, { state: 'PENDING', code: 'REGISTRATION_PENDING' });
const uncertain = () => response(202, { state: 'UNCERTAIN', code: 'REGISTRATION_UNCERTAIN' });
const originalCrypto = Object.getOwnPropertyDescriptor(window, 'crypto');
beforeEach(() => {
  jest.useFakeTimers();
  Object.defineProperty(window, 'crypto', { configurable: true, value: { getRandomValues: (array: Uint8Array) => array.fill(1) } });
});
afterEach(() => { jest.useRealTimers(); jest.restoreAllMocks(); if (originalCrypto) Object.defineProperty(window, 'crypto', originalCrypto); });
async function tick(ms = 1000) { jest.advanceTimersByTime(ms); for (let i = 0; i < 20; i++) await Promise.resolve(); }
async function finish<T>(promise: Promise<T>): Promise<T> {
  let done = false;
  void promise.then(() => { done = true; });
  for (let i = 0; i < 125 && !done; i++) await tick();
  return promise;
}
function setup() {
  const fetcher = jest.fn<Promise<Response>, [RequestInfo | URL, RequestInit?]>().mockResolvedValue(success());
  const recovery = createRegistrationRecovery('https://api.example/games/api/v1', fetcher);
  const controller = new AbortController();
  const methods = () => fetcher.mock.calls.map(([, options]) => options?.method);
  return { fetcher, recovery, controller, methods };
}

test('key uses a timestamp and 32 cryptographically generated bytes', () => {
  expect(registrationKey()).toMatch(/^v1\.\d{10}\.(01){32}$/);
});
test('first success uses the documented prefixed route, exact body, secret header and no persistence', async () => {
  const store = jest.spyOn(Storage.prototype, 'setItem');
  const { fetcher, recovery, controller } = setup();
  expect(await finish(recovery.start(input, controller.signal))).toEqual({ state: 'SUCCESS' });
  expect(fetcher).toHaveBeenCalledTimes(1);
  const [url, options] = fetcher.mock.calls[0];
  expect(url).toBe('https://api.example/games/api/v1/auth-recovery/registrations');
  expect(options).toMatchObject({ method: 'POST', credentials: 'include', cache: 'no-store', redirect: 'error', body: JSON.stringify(input) });
  expect(options?.headers).toHaveProperty('Idempotency-Key', expect.stringMatching(/^v1\./));
  expect(String(url)).not.toContain('v1.'); expect(store).not.toHaveBeenCalled();
  expect(recovery.canCheck()).toBe(false);
});
test('PENDING only reads status until success', async () => {
  const { fetcher, recovery, controller, methods } = setup();
  fetcher.mockResolvedValueOnce(pending()).mockResolvedValueOnce(pending());
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('SUCCESS');
  expect(methods()).toEqual(['POST', 'GET', 'GET']);
});
test('lost successful POST response is recovered through GET without replay', async () => {
  const { fetcher, recovery, controller, methods } = setup();
  fetcher.mockRejectedValueOnce(new TypeError('offline'));
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('SUCCESS');
  expect(methods()).toEqual(['POST', 'GET']);
  const postHeaders = fetcher.mock.calls[0][1]?.headers as Record<string, string>;
  const getHeaders = fetcher.mock.calls[1][1]?.headers as Record<string, string>;
  expect(getHeaders['Idempotency-Key']).toBe(postHeaders['Idempotency-Key']);
  expect(fetcher.mock.calls[1][1]?.body).toBeUndefined();
});
test('per-request timeout aborts the POST then safely checks status', async () => {
  const { fetcher, recovery, controller, methods } = setup();
  fetcher.mockImplementationOnce(() => new Promise(() => {}));
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('SUCCESS');
  expect(fetcher.mock.calls[0][1]?.signal?.aborted).toBe(true);
  expect(methods()).toEqual(['POST', 'GET']);
});
test('only NOT_FOUND permits replay with the exact key and original body', async () => {
  const { fetcher, recovery, controller, methods } = setup();
  fetcher.mockRejectedValueOnce(new Error()).mockResolvedValueOnce(response(404, { code: 'REGISTRATION_NOT_FOUND' }));
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('SUCCESS');
  expect(methods()).toEqual(['POST', 'GET', 'POST']);
  expect(fetcher.mock.calls[2][1]?.body).toBe(fetcher.mock.calls[0][1]?.body);
  expect(fetcher.mock.calls[2][1]?.headers).toEqual(fetcher.mock.calls[0][1]?.headers);
});
test('known RATE_LIMITED honors Retry-After before replaying the original POST', async () => {
  const { fetcher, recovery, controller, methods } = setup();
  fetcher.mockResolvedValueOnce(response(429, { state: 'RATE_LIMITED', code: 'AUTH_RATE_LIMITED' }, '10'));
  const result = recovery.start(input, controller.signal); await tick(); await tick(9000);
  expect(fetcher).toHaveBeenCalledTimes(1);
  expect((await finish(result)).state).toBe('SUCCESS');
  expect(methods()).toEqual(['POST', 'POST']);
});
test('general 429 only reads status after waiting; never infers safe POST replay', async () => {
  const { fetcher, recovery, controller, methods } = setup();
  fetcher.mockResolvedValueOnce(response(429, {}, '2'));
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('SUCCESS');
  expect(methods()).toEqual(['POST', 'GET']);
});
test('UNCERTAIN stops automatically; explicit status check retains key but never the POST body', async () => {
  const { fetcher, recovery, controller, methods } = setup(); fetcher.mockResolvedValueOnce(uncertain());
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('UNCERTAIN');
  expect(recovery.canCheck()).toBe(true);
  expect((await finish(recovery.check(controller.signal))).state).toBe('SUCCESS');
  expect(methods()).toEqual(['POST', 'GET']);
});
test.each([400, 403, 409, 410])('HTTP %s terminates without new keys or automatic requests', async status => {
  const { fetcher, recovery, controller } = setup(); fetcher.mockResolvedValueOnce(response(status, { message: input.password }));
  const result = await finish(recovery.start(input, controller.signal));
  expect(result.state).toBe('ERROR'); expect(JSON.stringify(result)).not.toContain(input.password);
  expect(fetcher).toHaveBeenCalledTimes(1); expect(recovery.canCheck()).toBe(false);
});
test('permanent outage after POST is uncertain and capped at six HTTP attempts', async () => {
  const { fetcher, recovery, controller, methods } = setup(); fetcher.mockRejectedValue(new Error('network'));
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('UNCERTAIN');
  expect(methods()).toEqual(['POST', 'GET', 'GET', 'GET', 'GET', 'GET']);
  expect(recovery.canCheck()).toBe(false);
});
test('retry delay beyond the total budget sends no further request', async () => {
  const { fetcher, recovery, controller } = setup(); fetcher.mockResolvedValueOnce(response(202, { state: 'PENDING' }, '121'));
  expect((await finish(recovery.start(input, controller.signal))).state).toBe('UNCERTAIN');
  expect(fetcher).toHaveBeenCalledTimes(1);
});
test('double start, cancellation and disposed receipts cannot restart registration', async () => {
  const { fetcher, recovery, controller } = setup(); fetcher.mockImplementationOnce(() => new Promise(() => {}));
  const first = recovery.start(input, controller.signal); await tick();
  expect((await recovery.start(input, controller.signal)).state).toBe('UNCERTAIN');
  controller.abort(); expect((await first).state).toBe('UNCERTAIN');
  recovery.dispose(); expect(recovery.canCheck()).toBe(false);
  await recovery.start(input, new AbortController().signal); expect(fetcher).toHaveBeenCalledTimes(1);
});
test('Retry-After and X-Retry-After use the longer delay including HTTP dates', () => {
  const headers = { get: (name: string) => name === 'Retry-After' ? '2' : new Date(Date.now() + 10000).toUTCString() } as Headers;
  expect(retryDelay(headers)).toBeGreaterThanOrEqual(9000);
});
